-- 0004 ledger: chart of accounts, periods and the append-only double-entry
-- journal. The rules that keep the books correct live HERE, in the database,
-- so no bug in any service (today's or a future one) can break them.

CREATE TABLE account (
  id              uuid PRIMARY KEY,
  tenant_id       uuid NOT NULL,
  legal_entity_id uuid NOT NULL,
  code            text NOT NULL CHECK (code ~ '^[0-9]{4}$'),
  name            text NOT NULL,
  kind            text NOT NULL CHECK (kind IN ('asset', 'liability', 'equity', 'income', 'expense')),
  UNIQUE (legal_entity_id, code),
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, legal_entity_id) REFERENCES legal_entity (tenant_id, id)
);

-- Accounting months. A locked period accepts no new entries; corrections go
-- into an open period as reversing entries.
CREATE TABLE period (
  id              uuid PRIMARY KEY,
  tenant_id       uuid NOT NULL,
  legal_entity_id uuid NOT NULL,
  starts_on       date NOT NULL,
  ends_on         date NOT NULL, -- exclusive
  status          text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'locked')),
  UNIQUE (legal_entity_id, starts_on),
  UNIQUE (tenant_id, id),
  CHECK (ends_on > starts_on),
  FOREIGN KEY (tenant_id, legal_entity_id) REFERENCES legal_entity (tenant_id, id)
);

CREATE TABLE journal_entry (
  id              uuid PRIMARY KEY,           -- UUIDv7, generated by the caller
  tenant_id       uuid NOT NULL,
  legal_entity_id uuid NOT NULL,
  source_type     text NOT NULL,              -- 'bill', later 'expense', 'payout', ...
  source_event_id uuid NOT NULL,              -- the business event this records
  entry_date      date NOT NULL,              -- tax point date (invoice date, IST)
  business_date   date,                       -- the restaurant's trading day, for day close
  period_id       uuid NOT NULL,
  reverses_id     uuid,
  memo            text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  -- One entry per business event, per tenant: posting is idempotent, and one
  -- tenant cannot probe another's ids by colliding with them.
  UNIQUE (tenant_id, source_event_id),
  FOREIGN KEY (tenant_id, legal_entity_id) REFERENCES legal_entity (tenant_id, id),
  FOREIGN KEY (tenant_id, period_id) REFERENCES period (tenant_id, id),
  FOREIGN KEY (tenant_id, reverses_id) REFERENCES journal_entry (tenant_id, id)
);

CREATE TABLE journal_line (
  entry_id   uuid NOT NULL,
  line_no    smallint NOT NULL CHECK (line_no > 0),
  tenant_id  uuid NOT NULL,
  account_id uuid NOT NULL,
  amount     bigint NOT NULL CHECK (amount <> 0), -- paise; debit > 0, credit < 0
  outlet_id  uuid,
  channel    text,                                -- dine_in, takeaway, swiggy, zomato, ...
  PRIMARY KEY (entry_id, line_no),
  FOREIGN KEY (tenant_id, entry_id) REFERENCES journal_entry (tenant_id, id),
  FOREIGN KEY (tenant_id, account_id) REFERENCES account (tenant_id, id)
);
CREATE INDEX journal_line_account ON journal_line (account_id);
CREATE INDEX journal_entry_date ON journal_entry (legal_entity_id, entry_date);

-- Invariant 1: every entry balances (sum of lines = 0), has at least two
-- lines, and only uses accounts of its own legal entity. The trigger is
-- DEFERRED: it runs at COMMIT, after all lines are in, so a half-written entry
-- is fine mid-transaction but can never be committed.
CREATE FUNCTION ledger_check_entry() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_entry uuid;
  v_sum   numeric;
  v_count integer;
  v_wrong integer;
BEGIN
  -- Two IF branches, not one CASE: PL/pgSQL would try to resolve NEW.id on a
  -- journal_line row (which has no id column) and fail.
  IF TG_TABLE_NAME = 'journal_entry' THEN
    v_entry := NEW.id;
  ELSE
    v_entry := NEW.entry_id;
  END IF;

  SELECT coalesce(sum(l.amount), 0), count(*) INTO v_sum, v_count
  FROM journal_line l WHERE l.entry_id = v_entry;

  IF v_count < 2 THEN
    RAISE EXCEPTION 'journal entry % has % line(s); at least 2 are required', v_entry, v_count
      USING ERRCODE = 'check_violation';
  END IF;
  IF v_sum <> 0 THEN
    RAISE EXCEPTION 'journal entry % does not balance: lines sum to % paise', v_entry, v_sum
      USING ERRCODE = 'check_violation';
  END IF;

  SELECT count(*) INTO v_wrong
  FROM journal_line l
  JOIN account a ON a.id = l.account_id
  JOIN journal_entry e ON e.id = l.entry_id
  WHERE l.entry_id = v_entry AND a.legal_entity_id <> e.legal_entity_id;
  IF v_wrong > 0 THEN
    RAISE EXCEPTION 'journal entry % uses accounts of another legal entity', v_entry
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END
$$;

CREATE CONSTRAINT TRIGGER journal_entry_balanced
  AFTER INSERT ON journal_entry DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION ledger_check_entry();
CREATE CONSTRAINT TRIGGER journal_line_balanced
  AFTER INSERT ON journal_line DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION ledger_check_entry();

-- Invariant 2: entries only go into an open period that contains their date.
-- FOR SHARE holds a lock on the period row until COMMIT, so an accountant
-- locking the month at the same moment waits for this entry instead of
-- racing past it.
CREATE FUNCTION ledger_check_period() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  p period%ROWTYPE;
BEGIN
  SELECT * INTO p FROM period WHERE id = NEW.period_id FOR SHARE;
  IF p.status <> 'open' THEN
    RAISE EXCEPTION 'period % is locked', p.starts_on USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.entry_date < p.starts_on OR NEW.entry_date >= p.ends_on THEN
    RAISE EXCEPTION 'entry date % is outside period %', NEW.entry_date, p.starts_on
      USING ERRCODE = 'check_violation';
  END IF;
  IF p.legal_entity_id <> NEW.legal_entity_id THEN
    RAISE EXCEPTION 'period belongs to another legal entity' USING ERRCODE = 'check_violation';
  END IF;
  NEW.created_at := now(); -- never trust a caller-supplied timestamp
  -- Remember, for this transaction only, that this entry is being written.
  -- The setting is transaction-local and is undone by ROLLBACK TO SAVEPOINT.
  PERFORM set_config('ledger.entries_in_tx',
    coalesce(current_setting('ledger.entries_in_tx', true), '') || NEW.id::text || ',', true);
  RETURN NEW;
END
$$;
CREATE TRIGGER journal_entry_period
  BEFORE INSERT ON journal_entry
  FOR EACH ROW EXECUTE FUNCTION ledger_check_period();

-- Invariant 2b: lines can only be added to an entry in the transaction that
-- created it. Without this, code could append a balanced pair of lines to a
-- posted entry next month (sum still zero, period check never re-run).
-- Scope: this stops bugs. A deliberately malicious app role could forge the
-- marker; the full fix is routing posting through one SECURITY DEFINER
-- function, planned with the accounting module.
CREATE FUNCTION ledger_check_line() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF position(NEW.entry_id::text || ',' IN coalesce(current_setting('ledger.entries_in_tx', true), '')) = 0 THEN
    RAISE EXCEPTION 'lines can only be added in the transaction that created entry %', NEW.entry_id
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER journal_line_same_tx
  BEFORE INSERT ON journal_line
  FOR EACH ROW EXECUTE FUNCTION ledger_check_line();

-- Invariant 2c: a locked period stays locked, and a period never moves.
-- Re-opening a month is an owner-level procedure, not something the app does.
CREATE FUNCTION ledger_period_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status = 'locked' AND NEW.status <> 'locked' THEN
    RAISE EXCEPTION 'period % is locked and cannot be re-opened by the application', OLD.starts_on
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF (NEW.starts_on, NEW.ends_on, NEW.legal_entity_id, NEW.tenant_id)
     IS DISTINCT FROM (OLD.starts_on, OLD.ends_on, OLD.legal_entity_id, OLD.tenant_id) THEN
    RAISE EXCEPTION 'a period''s dates and owner cannot change' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER period_guard
  BEFORE UPDATE ON period
  FOR EACH ROW EXECUTE FUNCTION ledger_period_guard();

-- Invariant 3: the journal is append-only. Nobody updates or deletes a posted
-- line, not even the owner role; a mistake is fixed with a reversing entry,
-- so the history of what was believed and when stays intact.
CREATE FUNCTION ledger_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'the journal is append-only: % on % is not allowed; post a reversing entry',
    TG_OP, TG_TABLE_NAME USING ERRCODE = 'insufficient_privilege';
END
$$;
CREATE TRIGGER journal_entry_append_only
  BEFORE UPDATE OR DELETE ON journal_entry
  FOR EACH ROW EXECUTE FUNCTION ledger_append_only();
CREATE TRIGGER journal_line_append_only
  BEFORE UPDATE OR DELETE ON journal_line
  FOR EACH ROW EXECUTE FUNCTION ledger_append_only();
CREATE TRIGGER journal_entry_no_truncate
  BEFORE TRUNCATE ON journal_entry
  FOR EACH STATEMENT EXECUTE FUNCTION ledger_append_only();
CREATE TRIGGER journal_line_no_truncate
  BEFORE TRUNCATE ON journal_line
  FOR EACH STATEMENT EXECUTE FUNCTION ledger_append_only();

